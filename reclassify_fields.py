def first(v):
    if isinstance(v, list):
        return v[0] if v else ""
    return v or ""

def main():
    apply = "--apply" in sys.argv
    with open(SRC, encoding="utf-8") as f:
        data = json.load(f)

    unmapped = []
    plan = []  # (新大項目, 新サブ)
    for i, q in enumerate(data):
        pf = first(q.get("new_fields", "")).strip()
        ps = first(q.get("new_sub_fields", "")).strip()
        key = (pf, ps)
        if key not in M:
            unmapped.append((i, q.get("id"), pf, ps))
            plan.append(None)
        else:
            plan.append(M[key])

    print("総問題数:", len(data))
    print("マッピング表エントリ数:", len(M))
    print("未マッピング件数:", len(unmapped))
    if unmapped:
        print("!!! 未マッピングがあるため中断します !!!")
        for i, qid, pf, ps in unmapped[:50]:
            print(f"  idx={i} id={qid} F=[{pf}] S=[{ps}]")
        sys.exit(1)

    # 新分布
    dist = defaultdict(lambda: defaultdict(int))
    for nf, ns in plan:
        dist[nf][ns] += 1
    print("\n=== 新分類分布 ===")
    for nf in sorted(dist):
        total = sum(dist[nf].values())
        print(f"\n【{nf}】計{total}問")
        for ns in sorted(dist[nf]):
            print(f"   {dist[nf][ns]:3}問  {ns}")

    if not apply:
        print("\n[DRY-RUN] 書き込みなし。--apply で適用。")
        return

    # バックアップ
    ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    bak = f"data.backup_{ts}.json"
    shutil.copy2(SRC, bak)
    print(f"\nバックアップ作成: {bak}")

    # 適用（旧値は _orig_sub / _orig_field に退避）
    for q, p in zip(data, plan):
        q["_orig_field"] = q.get("new_fields")
        q["_orig_sub"] = q.get("new_sub_fields")
        q["new_fields"] = [p[0]]
        q["new_sub_fields"] = [p[1]]

    with open(SRC, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=None)
    print("data.json を更新しました。")

if __name__ == "__main__":
    main()
